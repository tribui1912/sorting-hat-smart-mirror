#!/usr/bin/env python3
"""
mp3_to_header.py -- convert audio clips to C headers for the hat firmware.

    mp3/wav/... --ffmpeg--> raw PCM (signed 16-bit LE, mono, 22050 Hz) --> .h

The hat plays the arrays directly over I2S (ESP_I2S + MAX98357A, see
hat_firmware/hat_firmware.ino):

    I2S.write((uint8_t*)clip_pcm, clip_len * sizeof(int16_t));

Usage:
  python tools/mp3_to_header.py clip.mp3
  python tools/mp3_to_header.py voice/*.mp3
  python tools/mp3_to_header.py voice/ --norm --gain 3 --keep-pcm

Takes files and/or directories (non-recursive). Only dependency: ffmpeg
on PATH. Flash cost is rate * 2 bytes per second (44.1 KB/s at 22050 Hz).
"""

import argparse
import re
import struct
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
AUDIO_EXTS = {".mp3", ".wav", ".m4a", ".aac", ".ogg", ".oga", ".flac",
              ".opus", ".wma", ".aiff", ".aif"}


def die(msg):
    print(f"error: {msg}", file=sys.stderr)
    sys.exit(1)


def check_ffmpeg():
    try:
        subprocess.run(["ffmpeg", "-version"], capture_output=True, check=True)
    except (FileNotFoundError, subprocess.CalledProcessError):
        die("ffmpeg not found on PATH -- install it (winget install Gyan.FFmpeg)")


def gather_inputs(args):
    files = []
    for p in args:
        p = Path(p)
        if p.is_dir():
            found = sorted(f for f in p.iterdir() if f.suffix.lower() in AUDIO_EXTS)
            if not found:
                die(f"no audio files ({' '.join(sorted(AUDIO_EXTS))}) in {p}")
            files += found
        elif p.is_file():
            files.append(p)
        else:
            die(f"no such file or directory: {p}")
    return files


def c_symbol(stem):
    """File stem -> valid, collision-unlikely C identifier (kept lowercase-ish)."""
    s = re.sub(r"[^A-Za-z0-9_]", "_", stem)
    s = re.sub(r"_+", "_", s).strip("_")
    if not s or s[0].isdigit():
        s = "clip_" + s
    return s


def decode(src, pcm_path, rate, gain_db, norm):
    filters = []
    if norm:
        r = subprocess.run(
            ["ffmpeg", "-hide_banner", "-nostats", "-i", str(src),
             "-af", "volumedetect", "-f", "null", "-"],
            capture_output=True, text=True)
        m = re.search(r"max_volume:\s*(-?[\d.]+)\s*dB", r.stderr)
        peak = float(m.group(1)) if m else 0.0
        # leave room for a positive --gain so the final peak hits 0 dBFS, not the rails
        headroom = max(0.0, gain_db or 0.0)
        lift = -peak - headroom
        filters.append(f"volume={lift:.2f}dB")
    if gain_db is not None:
        filters.append(f"volume={gain_db:+.2f}dB")
    cmd = ["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-i", str(src)]
    if filters:
        cmd += ["-af", ",".join(filters)]
    cmd += ["-ar", str(rate), "-ac", "1", "-f", "s16le", str(pcm_path)]
    subprocess.run(cmd, check=True)


def write_header(pcm_path, hdr_path, src, sym, rate):
    raw = pcm_path.read_bytes()
    n_samples = len(raw) // 2
    duration = n_samples / rate

    lines = ["  " + ", ".join(f"{v:6d}" for v in chunk) + ","
             for chunk in _chunks(struct.iter_unpack("<h", raw), 12)]

    hdr_path.write_text(
        "// Auto-generated by tools/mp3_to_header.py -- DO NOT EDIT.\n"
        f"// source : {src.name}\n"
        f"// format : {rate} Hz, 16-bit mono PCM (signed, little-endian)\n"
        f"// size   : {n_samples} samples = {duration:.3f} s = {len(raw)} bytes in flash\n"
        "//\n"
        f"// play   : I2S.write((uint8_t*){sym}_pcm, {sym}_len * sizeof(int16_t));\n"
        "\n"
        "#pragma once\n"
        "#include <Arduino.h>\n"
        "\n"
        f"const int16_t {sym}_pcm[] PROGMEM = {{\n"
        + "\n".join(lines) +
        "\n};\n"
        f"const uint32_t {sym}_len = {n_samples};   // sample count\n", encoding="ascii")
    return n_samples, duration


def _chunks(iterable, size):
    buf = []
    for item in iterable:
        buf.append(item[0])
        if len(buf) == size:
            yield buf
            buf = []
    if buf:
        yield buf


def main():
    ap = argparse.ArgumentParser(
        description="Convert audio to 16-bit mono PCM C headers for the ESP32 hat.")
    ap.add_argument("inputs", nargs="+",
                    help="audio files and/or directories (non-recursive)")
    ap.add_argument("-o", "--out", type=Path,
                    default=REPO / "hat_firmware" / "audio",
                    help=f"output directory (default: {REPO / 'hat_firmware' / 'audio'})")
    ap.add_argument("--rate", type=int, default=22050,
                    help="sample rate (default 22050, matches firmware)")
    ap.add_argument("--gain", type=float, default=None, metavar="DB",
                    help="extra gain in dB, e.g. --gain 6 (applied after --norm; "
                         "norm leaves headroom so the result peaks at 0 dBFS)")
    ap.add_argument("--norm", action="store_true",
                    help="peak-normalize each clip to 0 dBFS")
    ap.add_argument("--keep-pcm", action="store_true",
                    help="keep the intermediate .pcm raw file")
    args = ap.parse_args()

    check_ffmpeg()
    files = gather_inputs(args.inputs)
    args.out.mkdir(parents=True, exist_ok=True)

    seen = {}
    for sym, f in ((c_symbol(f.stem), f) for f in files):
        if sym in seen:
            die(f"symbol collision: {f} and {seen[sym]} both map to '{sym}'")
        seen[sym] = f

    print(f"{len(files)} clip(s) -> {args.out}")
    for f in files:
        sym = c_symbol(f.stem)
        pcm_path = args.out / f"{sym}.pcm"
        hdr_path = args.out / f"{sym}.h"
        try:
            decode(f, pcm_path, args.rate, args.gain, args.norm)
            n, dur = write_header(pcm_path, hdr_path, f, sym, args.rate)
        except subprocess.CalledProcessError:
            die(f"ffmpeg failed on {f}")
        if not args.keep_pcm:
            pcm_path.unlink()
        print(f"  {f.name:<40} {sym}.h  ({dur:.2f} s, {n} samples, {n * 2} B)")

    print("usage in sketch:  #include \"audio/<name>.h\"  then  "
          "I2S.write((uint8_t*)<name>_pcm, <name>_len * sizeof(int16_t));")


if __name__ == "__main__":
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass
    main()
